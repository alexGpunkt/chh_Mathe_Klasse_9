-- ============================================================
-- Protokoll der Datenpflege
--
-- Ein Aufräumjob, den niemand beobachtet, ist ein Datenschutzversprechen
-- auf Verdacht. Jeder Lauf schreibt deshalb hierher: wann, wie lange, wie
